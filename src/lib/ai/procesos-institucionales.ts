function normalize(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

const STOPWORDS = new Set([
  'para', 'como', 'esta', 'este', 'estos', 'estas', 'pero', 'donde', 'cuando',
  'cuales', 'cual', 'quien', 'quienes', 'sobre', 'entre', 'hasta', 'desde',
  'debe', 'deben', 'puedo', 'puede', 'pueden', 'tengo', 'tiene', 'tienen',
  'hacer', 'realizar', 'necesito', 'requiere', 'requisitos', 'proceso',
  'procedimiento', 'tramite', 'que', 'quien', 'como', 'los', 'las', 'del',
  'una', 'uno', 'con', 'por', 'son', 'ser', 'esa', 'ese', 'eso', 'muy',
]);

function tokenize(text: string): string[] {
  return normalize(text)
    .split(/[^a-z0-9]+/)
    .filter(t => t.length >= 4 && !STOPWORDS.has(t));
}

/**
 * Busca, entre las preguntas frecuentes institucionales, las que de verdad
 * responden lo que pregunta el alumno. Compara por solapamiento de palabras
 * clave (no embeddings): es un FAQ fijo y curado, no material de clase, así
 * que no necesita el pipeline de vectores para algo de este tamaño.
 */
export function findProcesosRelevantes(
  question: string,
  options: { maxResults?: number; minScore?: number } = {}
): ProcesoQA[] {
  const { maxResults = 4, minScore = 2 } = options;
  const queryTokens = new Set(tokenize(question));
  if (queryTokens.size === 0) return [];

  const scored = PROCESOS_INSTITUCIONALES.map(qa => {
    const preguntaTokens = new Set(tokenize(qa.pregunta));
    const respuestaTokens = tokenize(qa.respuesta);

    let score = 0;
    for (const token of queryTokens) {
      if (preguntaTokens.has(token)) score += 3;
      else if (respuestaTokens.includes(token)) score += 1;
    }

    return { qa, score };
  });

  return scored
    .filter(({ score }) => score >= minScore)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxResults)
    .map(({ qa }) => qa);
}
